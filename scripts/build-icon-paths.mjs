// The app's icons as drawings (PLAN 10.5, TODO.md F17). Each Phosphor icon module carries all six
// of its weights, and the app draws two: bold everywhere, and fill for a few. This reads the icons
// listed in src/ui/icons.ts from @phosphor-icons/react, keeps only those weights, and writes them
// to src/ui/icons.gen.ts, which saves about a sixth of the JavaScript the app loads first.
//
//   npm run icon-paths     (after adding an icon to src/ui/icons.ts)

import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'

const root = new URL('..', import.meta.url)
const require = createRequire(import.meta.url)
const pkg = require('@phosphor-icons/react/package.json')
const defs = (name) => new URL(`node_modules/@phosphor-icons/react/dist/defs/${name}.es.js`, root)

// icon('Plus') draws bold only; icon('MapPin', 'fill') can be filled too
const list = await readFile(new URL('src/ui/icons.ts', root), 'utf8')
const wanted = [...list.matchAll(/\bicon\('(\w+)'(?:, '(fill)')?\)/g)].map(([, name, fill]) => [name, fill ? ['bold', 'fill'] : ['bold']])
if (!wanted.length) throw new Error('No icons found in src/ui/icons.ts')

// The definitions are React elements. A stand-in for React turns them into plain data.
const R = { Fragment: 'Fragment', createElement: (type, props, ...children) => ({ type, props: props ?? {}, children }) }
const parts = (el) => (el.type === 'Fragment' ? el.children.flatMap(parts) : [[el.type, el.props, ...(el.children.length ? [el.children.flatMap(parts)] : [])]])

const out = {}
for (const [name, weights] of wanted) {
  const code = await readFile(defs(name), 'utf8')
  const body = code
    .replace(/^import \* as (\w+) from "react";/m, 'const $1 = R;')
    .replace(/export \{\s*(\w+) as default\s*\};?\s*$/, 'return $1;')
  const map = new Function('R', body)(R)
  out[name] = Object.fromEntries(weights.map((w) => [w, parts(map.get(w))]))
}

const ts = `// Generated by scripts/build-icon-paths.mjs from @phosphor-icons/react ${pkg.version} (MIT): the bold
// weight of each icon in src/ui/icons.ts, and the fill weight where it's asked for. Don't edit by
// hand: run \`npm run icon-paths\`.

export type IconPart = readonly [tag: string, attrs: Readonly<Record<string, string | number>>, children?: readonly IconPart[]]

export const ICONS = ${JSON.stringify(out, null, 0)} as const satisfies Record<string, { bold: readonly IconPart[]; fill?: readonly IconPart[] }>
`
const target = new URL('src/ui/icons.gen.ts', root)
await writeFile(target, ts)
console.log(`Wrote src/ui/icons.gen.ts: ${wanted.length} icons, ${(ts.length / 1024).toFixed(1)} KB`)
