// Builds the "Jangal (જંગલ)" wordmark as SVG outlines (PLAN 6.11).
//
// The wordmark is Eczar Bold (700), upright (TODO.md F19). Eczar has no Gujarati, so જંગલ is
// drawn with Rasa Bold, upright too: Rasa comes from the same foundry, Rosetta, with the same
// calligraphic contrast. HarfBuzz does the shaping, so the Gujarati marks sit where the font says
// they should. The result is committed as src/ui/wordmark.gen.ts, so neither font is ever
// downloaded by the app, the exported page, or the PDF.
//
//   npm run wordmark
//
// The two font files are downloaded once from the Google Fonts repository into scripts/.cache.

import * as hb from 'harfbuzzjs'
import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('..', import.meta.url)
const cache = new URL('scripts/.cache/', root)

const FONTS = {
  latin: {
    file: 'Eczar.ttf',
    url: 'https://raw.githubusercontent.com/google/fonts/main/ofl/eczar/Eczar%5Bwght%5D.ttf',
    variations: { wght: 700 },
  },
  rasa: {
    file: 'Rasa.ttf',
    url: 'https://raw.githubusercontent.com/google/fonts/main/ofl/rasa/Rasa%5Bwght%5D.ttf',
    variations: { wght: 700 },
    // Rasa's Gujarati is drawn small for its em, so it's scaled up to sit level with Eczar
    size: Number(process.env.WM_RASA_SIZE ?? 1.3),
  },
}

// Each run is drawn in one font, in order: "Jangal (" and ")" in Eczar, the Gujarati in Rasa
const RUNS = [
  ['latin', 'Jangal ('],
  ['rasa', 'જંગલ'],
  ['latin', ')'],
]

const EM = 1000
const TRACKING = Number(process.env.WM_TRACKING ?? 0) // letter-spacing, in thousandths of an em

async function fontData(name) {
  const f = FONTS[name]
  const path = new URL(f.file, cache)
  if (!existsSync(path)) {
    await mkdir(cache, { recursive: true })
    console.log(`Downloading ${f.url}`)
    const res = await fetch(f.url)
    if (!res.ok) throw new Error(`Couldn't download ${f.file}: ${res.status}`)
    await writeFile(path, Buffer.from(await res.arrayBuffer()))
  }
  return (await readFile(path)).buffer
}

function openFont(name, data) {
  const face = new hb.Face(new hb.Blob(data))
  const font = new hb.Font(face)
  font.setVariations(Object.entries(FONTS[name].variations).map(([tag, value]) => new hb.Variation(tag, value)))
  return { font, face, scale: (EM / face.upem) * (FONTS[name].size ?? 1) }
}

const r = (n) => Math.round(n) // whole units are plenty at 1000 per em
const em = (n) => Math.round((n / EM) * 1000) / 1000

const fonts = {}
for (const name of Object.keys(FONTS)) fonts[name] = openFont(name, await fontData(name))

let pen = 0
let minY = Infinity
let maxY = -Infinity
let minX = Infinity
const parts = []
for (const [name, text] of RUNS) {
  const { font, scale } = fonts[name]
  const buf = new hb.Buffer()
  buf.addText(text)
  buf.guessSegmentProperties()
  hb.shape(font, buf)
  const infos = buf.getGlyphInfos()
  const positions = buf.getGlyphPositions()
  infos.forEach((info, i) => {
    const pos = positions[i]
    const ox = pen + pos.xOffset * scale
    const oy = pos.yOffset * scale
    let d = ''
    for (const cmd of font.glyphToJson(info.codepoint)) {
      const v = cmd.values
      const pts = []
      for (let k = 0; k < v.length; k += 2) {
        const x = ox + v[k] * scale
        const y = -(oy + v[k + 1] * scale) // SVG y points down
        minX = Math.min(minX, x)
        minY = Math.min(minY, y)
        maxY = Math.max(maxY, y)
        pts.push(`${r(x)} ${r(y)}`)
      }
      d += cmd.type + pts.join(' ')
    }
    parts.push(d)
    // Tracking applies between letters, not after marks with no advance
    pen += pos.xAdvance * scale + (pos.xAdvance ? TRACKING : 0)
  })
}
pen -= TRACKING

// The box hugs the drawn letters, with a little room. Eczar's own line height leaves space for
// Devanagari above and below, which would make the wordmark take up more room than it shows.
const PAD = 40
const ascent = Math.ceil(-minY) + PAD
const descent = Math.ceil(maxY) + PAD
const left = Math.min(0, Math.floor(minX))
const width = Math.ceil(pen - left)

const out = `// Generated by scripts/build-wordmark.mjs from Eczar Bold and Rasa Bold, upright.
// Don't edit by hand: run \`npm run wordmark\`.
// Units: 1000 per em. The baseline is y = 0, so the text sits ${ascent} units above it and ${descent} below.

export const WORDMARK = {
  text: 'Jangal (જંગલ)',
  viewBox: '${left} ${-ascent} ${width} ${ascent + descent}',
  /** Width and height in em, for sizing it like text */
  width: ${em(width)},
  height: ${em(ascent + descent)},
  /** How far the baseline sits above the bottom, in em */
  descent: ${em(descent)},
  d: '${parts.join('')}',
} as const
`
const target = process.env.WM_OUT ?? fileURLToPath(new URL('src/ui/wordmark.gen.ts', root))
await writeFile(target, out)
console.log(`Wrote ${target} (${(out.length / 1024).toFixed(1)} KB, ${width} x ${ascent + descent} units)`)
