// Writes the headers in deploy/headers.json into netlify.toml and vercel.json (PLAN 10.6), so the
// two hosts can never drift apart. Run with `npm run hosts` after changing deploy/headers.json.

import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('..', import.meta.url)
const { rules } = JSON.parse(await readFile(new URL('deploy/headers.json', root), 'utf8'))

// ---- netlify.toml: everything between the markers is generated
const toml = rules
  .map((r) => `[[headers]]\n  for = "${r.path}"\n  [headers.values]\n${Object.entries(r.headers).map(([k, v]) => `    ${k} = ${JSON.stringify(v)}`).join('\n')}`)
  .join('\n\n')
const netlifyPath = new URL('netlify.toml', root)
const netlify = await readFile(netlifyPath, 'utf8')
const START = '# ---- headers: generated by scripts/gen-host-config.mjs from deploy/headers.json'
const END = '# ---- end of generated headers'
const before = netlify.split(START)[0].trimEnd()
const after = netlify.includes(END) ? netlify.split(END)[1].trimStart() : ''
await writeFile(netlifyPath, `${before}\n\n${START}\n\n${toml}\n\n${END}\n${after ? `\n${after}` : ''}`)

// ---- vercel.json: its patterns use (.*) instead of *
const vercelPath = new URL('vercel.json', root)
const vercel = JSON.parse(await readFile(vercelPath, 'utf8'))
vercel.headers = rules.map((r) => ({
  source: r.path === '/*' ? '/(.*)' : r.path.replace(/\/\*$/, '/(.*)').replace(/^\/\*(\.[a-z]+)$/, '/(.*)$1'),
  headers: Object.entries(r.headers).map(([key, value]) => ({ key, value })),
}))
await writeFile(vercelPath, JSON.stringify(vercel, null, 2) + '\n')
console.log(`Wrote ${rules.length} header rules to netlify.toml and vercel.json`)
